    def _format_pipeline_status(self, pipeline: dict) -> str:
        """Format pipeline status for the update."""
        lines = []
        for status, data in pipeline.items():
            if data["count"] > 0:
                lines.append(f"- {status.replace('_', ' ').title()}: {data['count']} deals")
        return "\n".join(lines) if lines else "- No active deals in pipeline"

