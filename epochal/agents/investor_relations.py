from dataclasses import dataclass, field
from datetime import datetime
from typing import Optional
from enum import Enum

from epochal.agents.base import Agent, AgentRole, AgentTask, AgentResult, TaskStatus
from epochal.core.portfolio import Portfolio
from epochal.core.thesis import InvestmentThesis


class ContentType(Enum):
    """Types of content the IR agent can generate."""
    SUBSTACK_ARTICLE = "substack_article"
    LINKEDIN_POST = "linkedin_post"
    TWITTER_THREAD = "twitter_thread"
    INVESTOR_UPDATE = "investor_update"
    LP_LETTER = "lp_letter"
    PITCH_DECK_NARRATIVE = "pitch_deck_narrative"
    PRESS_RELEASE = "press_release"
    MARKET_COMMENTARY = "market_commentary"


class ContentTone(Enum):
    """Tone for content generation."""
    PROFESSIONAL = "professional"
    THOUGHT_LEADERSHIP = "thought_leadership"
    EDUCATIONAL = "educational"
    EXCITING = "exciting"
    ANALYTICAL = "analytical"


@dataclass
class ContentDraft:
    """A content draft generated by the IR agent."""
    content_type: ContentType
    title: str
    body: str
    summary: Optional[str] = None
    hashtags: list[str] = field(default_factory=list)
    call_to_action: Optional[str] = None
    target_audience: str = "investors"
    tone: ContentTone = ContentTone.PROFESSIONAL
    created_at: datetime = field(default_factory=datetime.utcnow)
    word_count: int = 0

    def __post_init__(self):
        self.word_count = len(self.body.split())

    def to_dict(self) -> dict:
        return {
            "content_type": self.content_type.value,
            "title": self.title,
            "body": self.body,
            "summary": self.summary,
            "hashtags": self.hashtags,
            "call_to_action": self.call_to_action,
            "target_audience": self.target_audience,
            "tone": self.tone.value,
            "created_at": self.created_at.isoformat(),
            "word_count": self.word_count,
        }


